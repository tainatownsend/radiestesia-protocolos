import assert from 'node:assert/strict';
import fs from 'node:fs';
const root=new URL('.',import.meta.url);
const read=(p)=>fs.readFileSync(new URL(p,root),'utf8');
const html=read('./index.html'),ui=read('./premium-workflow-ui.js'),css=read('./premium-workflow.css'),itemCss=read('./treatment-item-graphs.css'),trace=read('./traceability-ui.js');
